#!/usr/bin/env python3
"""Bundle the skill's documents into mcp/guide.js so the MCP server carries the instructions.
Single source of truth: skill/SKILL.md and skill/references/*.md, plus mcp/instructions.md.
Run from anywhere: python3 mcp/build_guide.py   (the deploy-mcp workflow does this before every deploy)."""
import json, re
from pathlib import Path

root = Path(__file__).resolve().parent.parent
skill = root / "skill"

def slug(h):
    s = re.sub(r"[^a-z0-9]+", "-", h.lower()).strip("-")
    return {"fully-automatic-the-user-sends-only-audio-and-captions": "workflow",
            "fast-remote-build-on-github-optional": "remote-build",
            "design-keep-it-the-same-as-the-website": "design",
            "site-look-updated-from-the-latest-website": "site-look",
            "brand-logos-and-animated-icons": "icons-and-logos",
            "sound-effects": "sound-effects",
            "word-by-word-highlight-optional": "word-highlight",
            "tamil-and-other-languages": "tamil-and-other-languages"}.get(s, s)

guides = {}
text = (skill / "SKILL.md").read_text(encoding="utf-8")
text = re.sub(r"^---.*?---\s*", "", text, count=1, flags=re.S)
for part in re.split(r"(?m)^## ", text)[1:]:
    head, _, body = part.partition("\n")
    guides[slug(head)] = f"# {head}\n{body.strip()}\n"
for f, key in (("scene-guide.md", "scene-guide"), ("design-system.md", "design-system"), ("channel-physics.md", "channel-physics")):
    p = skill / "references" / f
    if p.exists():
        guides[key] = p.read_text(encoding="utf-8")
guides.pop("files", None); guides.pop("environment-notes", None)  # local-sandbox details, not useful remotely

instr = (root / "mcp" / "instructions.md").read_text(encoding="utf-8")
out = "// GENERATED by mcp/build_guide.py from skill/ and mcp/instructions.md. Do not edit by hand.\n"
out += f"export const INSTRUCTIONS = {json.dumps(instr)};\nexport const GUIDES = {json.dumps(guides, ensure_ascii=False, indent=1)};\n"
(root / "mcp" / "guide.js").write_text(out, encoding="utf-8")
schema = (skill / "assets" / "channel-schema.json").read_text(encoding="utf-8")
(root / "mcp" / "schema.js").write_text("// GENERATED by mcp/build_guide.py from skill/assets/channel-schema.json. Do not edit by hand.\nexport const SCHEMA = " + schema + ";\n", encoding="utf-8")
print("guide.js:", len(guides), "topics:", ", ".join(sorted(guides)))
